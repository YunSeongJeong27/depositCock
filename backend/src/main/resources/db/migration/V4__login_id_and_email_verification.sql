-- 2026-11-20 사용자 결정: 로그인 아이디를 이메일과 따로 두고, 가입·비밀번호 찾기·휴대폰 변경에 이메일 인증번호를 쓴다.

-- 로그인 아이디. 새 아이디 규칙: 영문 소문자로 시작하는 영문 소문자·숫자·밑줄 4~20자, 소문자로 저장 (LoginIds).
-- 이미 있는 계정은 이메일 @ 앞부분(소문자, 20자까지)으로 채운다 (demo@… → demo, admin@… → admin).
-- 겹치면 가장 먼저 가입한 계정은 그대로 두고 나머지 뒤에 _판매자번호 를 붙인다 (demo@a, demo@b → demo, demo_7).
-- 이렇게 채운 아이디는 새 규칙에 안 맞을 수 있지만(점 등) 로그인은 된다. 관리자가 [정보 수정]에서 바꿀 수 있다.
ALTER TABLE seller ADD COLUMN login_id VARCHAR(30);
UPDATE seller SET login_id = SUBSTRING(LOWER(SUBSTRING(email, 1, POSITION('@' IN email) - 1)), 1, 20);
UPDATE seller SET login_id = login_id || '_' || CAST(id AS VARCHAR(9))
WHERE id NOT IN (SELECT MIN(id) FROM seller GROUP BY login_id);
ALTER TABLE seller ALTER COLUMN login_id SET NOT NULL;
ALTER TABLE seller ADD CONSTRAINT uq_seller_login_id UNIQUE (login_id);

-- 이메일 인증번호: 가입(SIGNUP), 비밀번호 찾기·변경(PASSWORD), 로그인한 판매자의 휴대폰 변경(PHONE).
-- 같은 용도·이메일로 새로 보내거나 가입·비밀번호·휴대폰 바꾸기에 쓰면 줄을 지운다. 유효 시간이 지나고 하루 뒤에도 지운다.
-- 인증번호는 해시로만 저장한다
CREATE TABLE email_verification (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purpose         VARCHAR(20)  NOT NULL,
    email           VARCHAR(255) NOT NULL,
    -- PASSWORD·PHONE 일 때 그 판매자 (가입 인증은 아직 판매자가 없어 비어 있음)
    seller_id       BIGINT REFERENCES seller (id) ON DELETE CASCADE,
    code_hash       VARCHAR(100) NOT NULL,
    sent_at         TIMESTAMP    NOT NULL,
    expires_at      TIMESTAMP    NOT NULL,
    failed_attempts INTEGER      NOT NULL DEFAULT 0,
    verified_at     TIMESTAMP,
    row_created_at  TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    row_updated_at  TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE INDEX idx_email_verification ON email_verification (purpose, email);
